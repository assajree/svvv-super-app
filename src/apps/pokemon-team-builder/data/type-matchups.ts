export function getSingleTypeAttack(attackerId: number, defenderId: number): number {
  if (attackerId <= 0 || defenderId <= 0) return 0
  const key = `${attackerId}:${defenderId}`
  return TYPE_ATTACK_MAP[key] ?? 0
}
